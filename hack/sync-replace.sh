#!/usr/bin/env bash
# sync-replace.sh regenerates the k8s.io/* staging replace block in go.mod.
#
# Why this exists (F15): k8s.io/kubernetes is not consumable as a library without
# replacing its 33 staging modules. The upstream go.mod replaces them with
# ./staging/src/k8s.io/<name>; an out-of-tree module must replace them with the
# published module versions instead, otherwise `go mod tidy` fails with
#   k8s.io/api/apps/v1beta2: reading k8s.io/api/go.mod at revision v0.0.0:
#   unknown revision v0.0.0
#
# Usage: hack/sync-replace.sh [kube-version] [staging-version]
#   defaults: v1.36.5 v0.36.5
# Re-run this whenever k8s.io/kubernetes is upgraded.
set -euo pipefail

KUBE_VERSION="${1:-v1.36.5}"
STAGING_VERSION="${2:-v0.36.5}"
GOMOD="${GOMOD:-go.mod}"

begin_marker="// BEGIN k8s-staging-replace"
end_marker="// END k8s-staging-replace"

upstream_dir="$(go mod download -json "k8s.io/kubernetes@${KUBE_VERSION}" | sed -n 's/.*"Dir": *"\([^"]*\)".*/\1/p')"
if [[ -z "${upstream_dir}" || ! -f "${upstream_dir}/go.mod" ]]; then
	echo "sync-replace: cannot locate k8s.io/kubernetes@${KUBE_VERSION} go.mod" >&2
	exit 1
fi

replacements="$(grep -E '^[[:space:]]+k8s\.io/[a-z-]+ => \./staging/' "${upstream_dir}/go.mod" |
	sed -E "s#^[[:space:]]+(k8s\.io/[a-z-]+) => \./staging/.*#\1 => \1 ${STAGING_VERSION}#")"

count="$(printf '%s\n' "${replacements}" | wc -l | tr -d ' ')"
if [[ "${count}" -eq 0 ]]; then
	echo "sync-replace: upstream go.mod has no staging replaces, aborting" >&2
	exit 1
fi

tmp="$(mktemp)"
{
	echo "${begin_marker} (generated by hack/sync-replace.sh, do not edit by hand)"
	printf 'replace (\n%s\n)\n' "${replacements}"
	echo "${end_marker}"
} >"${tmp}"
block="${tmp}"

python3 - "${GOMOD}" "${block}" "${begin_marker}" "${end_marker}" <<'PY'
import sys

gomod, block_path, begin, end = sys.argv[1:5]
new_block = open(block_path, encoding="utf-8").read().rstrip("\n")
lines = open(gomod, encoding="utf-8").read().splitlines()

out, i, replaced = [], 0, False
while i < len(lines):
    if lines[i].startswith(begin):
        out.extend(new_block.splitlines())
        replaced = True
        while i < len(lines) and not lines[i].startswith(end):
            i += 1
        i += 1  # skip the old end marker
        continue
    out.append(lines[i])
    i += 1

if not replaced:
    out.extend(["", new_block])

open(gomod, "w", encoding="utf-8").write("\n".join(out).rstrip("\n") + "\n")
PY
rm -f "${tmp}"

echo "sync-replace: wrote ${count} k8s.io/* staging replaces (${KUBE_VERSION} -> ${STAGING_VERSION})"
