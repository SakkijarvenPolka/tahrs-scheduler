// Command gen-rbac writes deploy/base/clusterrole.yaml from the upstream
// kube-scheduler ClusterRoles, so the tahrs-scheduler permissions can be diffed
// against the release they were derived from instead of being copied by hand.
//
// Source:
//
//	k8s.io/kubernetes/plugin/pkg/auth/authorizer/rbac/bootstrappolicy/policy.go
//	  - ClusterRole system:kube-scheduler  (policy.go:670)
//	  - ClusterRole system:volume-scheduler (policy.go:528)
//
// Deviations from the upstream roles, all deliberate:
//
//   - Lease permissions are removed from this ClusterRole entirely (plan §7).
//     Upstream keeps them here with a TODO to scope them to kube-system, but a
//     ClusterRole bound cluster-wide grants lease access in every namespace.
//     Leader election only touches tahrs-system/tahrs-scheduler, so the rules
//     live in the namespaced Role deploy/base/role-lease.yaml instead.
//   - The role is named tahrs-scheduler-role, so it never collides with the
//     default system:kube-scheduler role that k3s and kubeadm create.
//   - The kube-system ConfigMap read (extension-apiserver-authentication) lives
//     in a namespaced Role instead of this ClusterRole: a ClusterRoleBinding
//     would grant ConfigMap reads in every namespace (see deploy/base/role-kube-system.yaml).
package main

import (
	"flag"
	"fmt"
	"os"
	"strings"

	rbacv1 "k8s.io/api/rbac/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"sigs.k8s.io/yaml"

	"k8s.io/kubernetes/plugin/pkg/auth/authorizer/rbac/bootstrappolicy"
)

const (
	roleName   = "tahrs-scheduler-role"
	sourceNote = "Generated by hack/gen-rbac from k8s.io/kubernetes/plugin/pkg/auth/authorizer/rbac/bootstrappolicy/policy.go (system:kube-scheduler + system:volume-scheduler). Do not edit by hand; run `make rbac`."
)

func main() {
	output := flag.String("output", "deploy/base/clusterrole.yaml", "file to write")
	flag.Parse()

	upstream := map[string]rbacv1.ClusterRole{}
	for _, role := range bootstrappolicy.ClusterRoles() {
		upstream[role.Name] = role
	}
	scheduler, ok := upstream["system:kube-scheduler"]
	if !ok {
		fail("system:kube-scheduler not found in bootstrappolicy")
	}
	volume, ok := upstream["system:volume-scheduler"]
	if !ok {
		fail("system:volume-scheduler not found in bootstrappolicy")
	}

	rules := make([]rbacv1.PolicyRule, 0, len(scheduler.Rules)+len(volume.Rules))
	for _, rule := range scheduler.Rules {
		if hasResource(rule, "leases") || hasResource(rule, "leasecandidates") {
			// Granted by deploy/base/role-lease.yaml in tahrs-system instead;
			// leasecandidates is a pre-GA resource the tahrs scheduler never
			// touches.
			continue
		}
		rules = append(rules, rule)
	}
	rules = append(rules, volume.Rules...)

	role := rbacv1.ClusterRole{
		TypeMeta: metav1.TypeMeta{APIVersion: "rbac.authorization.k8s.io/v1", Kind: "ClusterRole"},
		ObjectMeta: metav1.ObjectMeta{
			Name: roleName,
			Annotations: map[string]string{
				"tahrs.dev/source": sourceNote,
			},
		},
		Rules: rules,
	}

	body, err := yaml.Marshal(role)
	if err != nil {
		fail("marshal: %v", err)
	}
	header := "# " + sourceNote + "\n" +
		"# Upstream rules keep their original order. Lease permissions are not part of this\n" +
		"# role: leader election only needs tahrs-system/tahrs-scheduler, so they are granted\n" +
		"# by the namespaced Role in deploy/base/role-lease.yaml (plan §7).\n"
	if err := os.WriteFile(*output, append([]byte(header), body...), 0o644); err != nil {
		fail("write %s: %v", *output, err)
	}
	fmt.Printf("wrote %s (%d rules)\n", *output, len(rules))
}

func hasResource(rule rbacv1.PolicyRule, name string) bool {
	for _, r := range rule.Resources {
		if r == name || strings.HasPrefix(r, name+"/") {
			return true
		}
	}
	return false
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen-rbac: "+format+"\n", args...)
	os.Exit(1)
}
